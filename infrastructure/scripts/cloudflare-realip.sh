#!/bin/bash
# Regenerate infrastructure/nginx/realip.conf from Cloudflare's live IP ranges.
# Run on the server whenever Cloudflare announces new ranges (a few times/year):
#
#   ./scripts/cloudflare-realip.sh && docker compose restart nginx
#
# Requires curl + jq.
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
OUT="${HERE}/../nginx/realip.conf"

{
  echo "# Generated by scripts/cloudflare-realip.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# Source: https://www.cloudflare.com/ips-v4 and /ips-v6"
  echo "real_ip_header X-Forwarded-For;"
  echo "real_ip_recursive on;"
  echo
  curl -fsS https://www.cloudflare.com/ips-v4 | sed 's/^/set_real_ip_from /; s/$/;/'
  curl -fsS https://www.cloudflare.com/ips-v6 | sed 's/^/set_real_ip_from /; s/$/;/'
} > "${OUT}"

echo "Wrote ${OUT}. Reload nginx: docker compose restart nginx"
